import Foundation
import Testing
@testable import MacventoryCore

@Suite("Modern Toolbox launcher evidence")
struct ToolboxModernTests {
    @Test func modernGeneratedLauncherMatchesExactIDE() async throws {
        let box = try Sandbox(); defer { box.clean() }
        let path = try box.app("Applications/IntelliJ IDEA.app", id: "com.jetbrains.idea", name: "IntelliJ IDEA")
        try box.write("Toolbox/scripts/idea", "#!/bin/bash\n#Generated by JetBrains Toolbox 3.4.3.81140 at 2026-05-28\nopen -na \"\(path)/Contents/MacOS/idea\" --args \"$@\"\n")
        let result = try await ToolboxScanner(roots: [], managementRoot: box.root.appendingPathComponent("Toolbox").path, scriptRoots: [box.root.appendingPathComponent("Toolbox/scripts").path]).scan()
        #expect(result.items.count == 1)
        #expect(result.items[0].path == FileSystem.canonical(path))
        #expect(result.items[0].confidence == .inferred)
        #expect(result.items[0].attributes["Toolbox detection"] == "Modern generated launcher")
    }
    @Test func rejectsNameOnlyScriptsDynamicTargetsAndMissingGenerator() {
        for text in ["open -na '/Applications/IntelliJ IDEA.app'", "#Generated by JetBrains Toolbox 3.0\nopen -na \"$HOME/Applications/IDE.app\"", "#Generated by JetBrains Toolbox 3.0\nopen -na \"/Applications/$(bad).app\""] {
            #expect(ToolboxScanner.launcherPaths(text).isEmpty)
        }
    }
    @Test func staleLauncherDoesNotInventAnInstallation() async throws {
        let box = try Sandbox(); defer { box.clean() }
        try box.write("scripts/idea", "#Generated by JetBrains Toolbox 3.0\nopen -na '/nonexistent-macventory-test/IDE.app'")
        let result = try await ToolboxScanner(roots: [], managementRoot: box.root.path, scriptRoots: [box.root.appendingPathComponent("scripts").path]).scan()
        #expect(result.items.isEmpty)
        #expect(result.report.state == .unsupported)
    }
    @Test func managerAndNativeDiscoveriesStillMerge() async throws {
        let box = try Sandbox(); defer { box.clean() }
        let path = try box.app("IDE.app", id: "com.jetbrains.idea")
        try box.write("scripts/idea", "#Generated by JetBrains Toolbox 3.0\nopen -na '\(path)'")
        let result = try await ToolboxScanner(roots: [], managementRoot: box.root.path, scriptRoots: [box.root.appendingPathComponent("scripts").path]).scan()
        let merged = InventoryMerger.merge(result.items + [try NativeScanner.item(at: path)])
        #expect(merged.count == 1)
        #expect(merged[0].primarySource == .toolbox)
    }
}
